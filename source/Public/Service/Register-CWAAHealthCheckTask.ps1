function Register-CWAAHealthCheckTask {
    <#
    .SYNOPSIS
        Creates or updates a scheduled task for periodic ConnectWise Automate agent health checks.
    .DESCRIPTION
        Creates a Windows scheduled task that runs Repair-CWAA at a configurable interval
        (default every 6 hours) to monitor agent health and automatically remediate issues.

        The task runs as SYSTEM with highest privileges, includes a random delay equal to the
        interval to stagger execution across multiple machines, and has a 1-hour execution timeout.

        If the task already exists and its configuration (InstallerToken, Server, LocationID, or
        IntervalHours) has changed, the task is replaced in place to match. Use -Force to
        replace it unconditionally. A failed replacement leaves the existing task as it was.

        Returns an object with TaskName, Created and Updated. Created is true when a new task
        was registered and Updated when an existing one was replaced (including with -Force);
        both are false when nothing changed, with -WhatIf, or on failure. A failure is written
        to the Application event log (4022 when the task could not be created, 4023 when it
        was created but is missing afterwards) and reported as an error that follows
        -ErrorAction.

        A backup of the current agent configuration is created before task registration
        via New-CWAABackup.
    .PARAMETER InstallerToken
        The installer token for authenticated agent deployment. Embedded in the scheduled
        task action for use by Repair-CWAA.
    .PARAMETER Server
        Optional server URL. When provided, the scheduled task passes this to Repair-CWAA
        in Install mode (with Server, LocationID, and InstallerToken).
    .PARAMETER LocationID
        Optional location ID. Required when Server is provided.
    .PARAMETER TaskName
        Name of the scheduled task. Default: 'AAutomate'.
    .PARAMETER IntervalHours
        Hours between health check runs. Default: 6.
    .PARAMETER Force
        Force recreation of the task even if it already exists with a matching configuration.
    .EXAMPLE
        Register-CWAAHealthCheckTask -InstallerToken 'abc123def456'
        Creates a task that runs Repair-CWAA in Checkup mode every 6 hours.
    .EXAMPLE
        Register-CWAAHealthCheckTask -InstallerToken 'token' -Server 'https://automate.domain.com' -LocationID 42
        Creates a task that runs Repair-CWAA in Install mode (can install fresh if agent is missing).
    .EXAMPLE
        Register-CWAAHealthCheckTask -InstallerToken 'token' -IntervalHours 12 -TaskName 'MyHealthCheck'
        Creates a custom-named task running every 12 hours.
    .EXAMPLE
        Get-CWAAInfo | Register-CWAAHealthCheckTask -InstallerToken 'token'
        Uses Server and LocationID from the installed agent via pipeline to register a health check task.
    .NOTES
        Author: Chris Taylor
        Alias: Register-LTHealthCheckTask
    .LINK
        https://github.com/christaylorcodes/ConnectWiseAutomateAgent
    .PARAMETER ProgressAction
        Determines how PowerShell responds to progress updates generated by a script, cmdlet, or provider.
        #>
    [CmdletBinding(SupportsShouldProcess = $True)]
    [Alias('Register-LTHealthCheckTask')]
    Param(
        [Parameter(Mandatory = $True)]
        [ValidatePattern('(?s:^[0-9a-z]+$)')]
        [string]$InstallerToken,

        [Parameter(ValueFromPipelineByPropertyName = $True)]
        [ValidatePattern('^[a-zA-Z0-9\.\-\:\/]+$')]
        [string[]]$Server,

        [Parameter(ValueFromPipelineByPropertyName = $True)]
        [int]$LocationID,

        [ValidatePattern('^[\w\-\. ]+$')]
        [string]$TaskName = 'AAutomate',

        [ValidateRange(1, 168)]
        [int]$IntervalHours = 6,

        [switch]$Force
    )

    Begin {
        Write-Debug "Starting $($MyInvocation.InvocationName)"
    }

    Process {
        $created = $False
        $updated = $False

        # Build the PowerShell command for the scheduled task action
        # Use Install mode if Server and LocationID are provided, otherwise Checkup mode
        if ($Server -and $LocationID) {
            # Build a proper PowerShell array literal for the Server argument.
            # Handles both single-server and multi-server arrays from Get-CWAAInfo pipeline.
            $serverArgument = ($Server | ForEach-Object { "'$_'" }) -join ','
            $repairCommand = "Import-Module ConnectWiseAutomateAgent; Repair-CWAA -Server $serverArgument -LocationID $LocationID -InstallerToken '$InstallerToken'"
        }
        else {
            $repairCommand = "Import-Module ConnectWiseAutomateAgent; Repair-CWAA -InstallerToken '$InstallerToken'"
        }

        # XML-escape special characters in the command for the task definition
        $escapedCommand = $repairCommand -replace '&', '&amp;' -replace '<', '&lt;' -replace '>', '&gt;' -replace '"', '&quot;' -replace "'", '&apos;'
        $intervalIso = "PT${IntervalHours}H"

        # Check if the task already exists
        $existingTaskXml = $Null
        Try {
            [xml]$existingTaskXml = schtasks /QUERY /XML /TN $TaskName 2>$Null
        }
        Catch { Write-Debug "Task '$TaskName' not found or query failed: $($_.Exception.Message)" }

        # If the task exists and both its command (token/server/locationid) and interval already match,
        # skip recreation unless -Force. schtasks returns XML-decoded text, so compare against the raw
        # (unescaped) command, not $escapedCommand.
        if ($existingTaskXml -and -not $Force) {
            $configMatches = $existingTaskXml.Task.Actions.Exec.Arguments -match [regex]::Escape($repairCommand)
            $intervalMatches = $existingTaskXml.Task.Triggers.TimeTrigger.Repetition.Interval -eq $intervalIso
            if ($configMatches -and $intervalMatches) {
                Write-Verbose "Scheduled task '$TaskName' already exists with matching configuration. Use -Force to recreate."
                [PSCustomObject]@{
                    TaskName = $TaskName
                    Created  = $False
                    Updated  = $False
                }
                return
            }
        }
        # Replacing a task that is already there (drifted, or -Force) is an update, not a creation
        $taskExisted = [bool]$existingTaskXml

        if ($PSCmdlet.ShouldProcess("Scheduled Task '$TaskName'", 'Create health check task')) {
            # Back up agent settings before creating/updating the task
            Write-Verbose 'Backing up agent configuration.'
            New-CWAABackup -ErrorAction SilentlyContinue

            # Build the task XML definition
            # Runs as SYSTEM (S-1-5-18) with highest privileges
            # Repeats every $IntervalHours hours with randomized delay for staggering
            $startBoundary = Get-Date -Format 'yyyy-MM-ddTHH:mm:ssK'

            [xml]$taskXml = @"
<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
    <RegistrationInfo>
        <Description>ConnectWise Automate agent health check and automatic remediation.</Description>
        <URI>\$TaskName</URI>
    </RegistrationInfo>
    <Principals>
        <Principal id="Author">
            <UserId>S-1-5-18</UserId>
            <RunLevel>HighestAvailable</RunLevel>
        </Principal>
    </Principals>
    <Settings>
        <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
        <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
        <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
        <IdleSettings>
            <Duration>PT10M</Duration>
            <WaitTimeout>PT1H</WaitTimeout>
            <StopOnIdleEnd>false</StopOnIdleEnd>
            <RestartOnIdle>false</RestartOnIdle>
        </IdleSettings>
        <ExecutionTimeLimit>PT1H</ExecutionTimeLimit>
    </Settings>
    <Triggers>
        <TimeTrigger>
            <StartBoundary>$startBoundary</StartBoundary>
            <Repetition>
                <Interval>$intervalIso</Interval>
                <Duration>P7300D</Duration>
                <StopAtDurationEnd>true</StopAtDurationEnd>
            </Repetition>
            <RandomDelay>$intervalIso</RandomDelay>
        </TimeTrigger>
    </Triggers>
    <Actions Context="Author">
        <Exec>
            <Command>C:\WINDOWS\System32\WindowsPowerShell\v1.0\powershell.exe</Command>
            <Arguments>-NoProfile -WindowStyle Hidden -Command "$escapedCommand"</Arguments>
        </Exec>
    </Actions>
</Task>
"@

            # Unique name: the file holds the InstallerToken, and a fixed name would let two
            # registrations running at once overwrite or delete each other's file
            $taskFilePath = Join-Path $env:TEMP ('CWAAHealthCheckTask-{0}.xml' -f [guid]::NewGuid().ToString('N'))
            $failureEventId = $Null
            # With an effective ErrorActionPreference of Stop, Windows PowerShell turns redirected
            # native stderr into a terminating error, so relax it for the schtasks calls. The caller's
            # preference is applied again when the failure is reported below.
            $callerErrorAction = $ErrorActionPreference
            $ErrorActionPreference = 'Continue'
            Try {
                $taskXml.Save($taskFilePath)

                # /F replaces an existing task in place, so a failed create leaves the old task intact
                $schtasksOutput = schtasks /CREATE /TN $TaskName /XML $taskFilePath /RU SYSTEM /F 2>&1
                if ($LASTEXITCODE -ne 0) {
                    throw "schtasks returned exit code $LASTEXITCODE. Output: $schtasksOutput"
                }

                # Verify the task actually persists after creation — a task can be reported as created
                # successfully by schtasks and then be removed immediately afterward (e.g. by AV/policy).
                # Uses schtasks (not Get-ScheduledTask/ScheduledTasks module) to match this function's
                # PowerShell 3.0 compatibility target and the existence check above.
                $Null = schtasks /QUERY /TN $TaskName 2>&1
                if ($LASTEXITCODE -ne 0) {
                    $failureEventId = 4023
                    $failureMessage = "Task '$TaskName' reported successful creation but could not be found on verification (possible AV/policy removal)."
                }
            }
            Catch {
                $failureEventId = 4022
                $failureMessage = "Failed to create scheduled task '$TaskName'. Error: $($_.Exception.Message)"
            }
            Finally {
                # Clean up the temporary XML file
                Remove-Item -Path $taskFilePath -Force -ErrorAction SilentlyContinue
                # Put back for the next pipeline record, which captures it again
                $ErrorActionPreference = $callerErrorAction
            }

            if ($failureEventId) {
                # Event log first, so it is written even when the caller's -ErrorAction Stop makes
                # Write-Error terminate.
                Write-CWAAEventLog -EventId $failureEventId -EntryType Error -Message $failureMessage
                Write-Error $failureMessage -ErrorAction $callerErrorAction
            }
            else {
                $updated = $taskExisted
                $created = -not $taskExisted
                $resultMessage = if ($updated) { "Scheduled task '$TaskName' updated." } else { "Scheduled task '$TaskName' created." }
                Write-Output $resultMessage
                Write-CWAAEventLog -EventId 4020 -EntryType Information -Message "$resultMessage Interval: every $IntervalHours hours."
            }
        }

        [PSCustomObject]@{
            TaskName = $TaskName
            Created  = $created
            Updated  = $updated
        }
    }

    End {
        Write-Debug "Exiting $($MyInvocation.InvocationName)"
    }
}
