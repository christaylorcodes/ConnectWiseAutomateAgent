function Initialize-CWAAScriptLog {
    <#
    .SYNOPSIS
        Initializes a log file for ConnectWise Automate script execution.
    .DESCRIPTION
        Creates a timestamped log file in the specified directory and returns the full path.
        The log file is ready for use with Write-CWAAScriptLog. No external modules are required.

        Default log directory is the standard Automate agent log location
        (the logs folder under the agent install path, $env:windir\LTSvc\logs by default). The log filename is derived from the calling script or
        function name with a timestamp suffix.

        This replaces Initialize-AutomateLogging from the legacy CW-Automate-ScriptHelper.ps1
        which depended on the PSGallery Logging module. All logging is now synchronous file
        writes with no async queue.
    .PARAMETER LogDirectory
        The directory where the log file will be created. Defaults to the logs folder under the agent install path ($env:windir\LTSvc\logs).
        The directory will be created if it does not exist.
    .PARAMETER LogName
        The base name for the log file. Defaults to the name of the calling script or function
        (determined from Get-PSCallStack). A timestamp is appended automatically.
    .EXAMPLE
        $logPath = Initialize-CWAAScriptLog
        Write-CWAAScriptLog -Message 'Script started' -LogPath $logPath
    .EXAMPLE
        $logPath = Initialize-CWAAScriptLog -LogDirectory 'C:\Logs' -LogName 'MyScript'
    .NOTES
        Author: Chris Taylor
        Alias: Initialize-AutomateLogging
    .LINK
        https://github.com/christaylorcodes/ConnectWiseAutomateAgent
    .PARAMETER ProgressAction
        Determines how PowerShell responds to progress updates generated by a script, cmdlet, or provider.
    #>
    [CmdletBinding()]
    [Alias('Initialize-AutomateLogging')]
    Param(
        [Parameter()]
        [string]$LogDirectory = (Join-Path -Path $Script:CWAAInstallPath -ChildPath 'logs'),

        [Parameter()]
        [string]$LogName
    )

    Begin {
        Write-Debug "Starting $($MyInvocation.InvocationName)"
    }

    Process {
        Try {
            # Derive log name from calling context if not specified
            if (-not $LogName) {
                $callStack = Get-PSCallStack
                if ($callStack.Count -gt 1) { $LogName = [string]$callStack[1].Command }
                # Strip .ps1 extension if present
                $LogName = $LogName -replace '\.ps1$', ''
            }

            # Drop characters that are illegal in file names (e.g. '<ScriptBlock>' from a -Command caller)
            $invalidChars = [System.IO.Path]::GetInvalidFileNameChars()
            $LogName = -join ($LogName.ToCharArray() | Where-Object { $invalidChars -notcontains $_ })
            if (-not $LogName) { $LogName = 'CWAAScript' }

            # Ensure log directory exists
            if (-not (Test-Path -Path $LogDirectory)) {
                $null = New-Item -Path $LogDirectory -ItemType Directory -Force
                Write-Debug "Initialize-CWAAScriptLog: Created log directory '$LogDirectory'."
            }

            # Build timestamped filename
            $timestamp = Get-Date -Format 'yyyyMMdd-HHmmss'
            $logFileName = "${LogName}_${timestamp}.log"
            $logFilePath = Join-Path -Path $LogDirectory -ChildPath $logFileName

            # Writing the header creates the file
            Write-CWAAScriptLog -Message "Log initialized: $LogName" -LogPath $logFilePath -ErrorAction Stop

            $logFilePath
        }
        Catch {
            Write-Error "Failed to initialize script log in '$LogDirectory'. Error: $($_.Exception.Message)"
        }
    }

    End {
        Write-Debug "Exiting $($MyInvocation.InvocationName)"
    }
}
