function Initialize-CWAAScriptLog {
    <#
    .SYNOPSIS
        Initializes a log file for ConnectWise Automate script execution.
    .DESCRIPTION
        Creates a timestamped log file in the specified directory and returns the full path.
        The log file is ready for use with Write-CWAAScriptLog. No external modules are required.

        Default log directory is the standard Automate agent log location
        (the logs folder under the agent install path, $env:windir\LTSvc\logs by default). The log filename is derived from the calling script or
        function name with a millisecond timestamp suffix (Name_yyyyMMdd-HHmmss-fff.log).

        The returned path is absolute. The file is created exclusively: if a file (or link)
        already exists at that path the call fails rather than appending to it, and a log
        directory whose path runs through a junction or symbolic link is refused. On failure a non-terminating error is written
        and nothing is returned; use -ErrorAction Stop to make failures terminating.

        Logs under the agent folder are typically readable by local users. Do not log secrets.

        This replaces Initialize-AutomateLogging from the legacy CW-Automate-ScriptHelper.ps1
        which depended on the PSGallery Logging module. All logging is now synchronous file
        writes with no async queue.
    .PARAMETER LogDirectory
        The directory where the log file will be created. Defaults to the logs folder under the agent install path ($env:windir\LTSvc\logs).
        The directory will be created if it does not exist.
    .PARAMETER LogName
        The base name for the log file. Defaults to the name of the calling script or function
        (determined from Get-PSCallStack). A timestamp is appended automatically.
    .EXAMPLE
        $logPath = Initialize-CWAAScriptLog
        Write-CWAAScriptLog -Message 'Script started' -LogPath $logPath
    .EXAMPLE
        $logPath = Initialize-CWAAScriptLog -LogDirectory 'C:\Logs' -LogName 'MyScript'
    .NOTES
        Author: Chris Taylor
        Alias: Initialize-AutomateLogging
    .LINK
        https://github.com/christaylorcodes/ConnectWiseAutomateAgent
    .PARAMETER ProgressAction
        Determines how PowerShell responds to progress updates generated by a script, cmdlet, or provider.
    #>
    [CmdletBinding()]
    [Alias('Initialize-AutomateLogging')]
    Param(
        [Parameter()]
        [string]$LogDirectory = (Join-Path -Path $Script:CWAAInstallPath -ChildPath 'logs'),

        [Parameter()]
        [string]$LogName
    )

    Begin {
        Write-Debug "Starting $($MyInvocation.InvocationName)"
    }

    Process {
        $created = $false
        Try {
            if (-not $LogName) {
                $callStack = Get-PSCallStack
                if ($callStack.Count -gt 1) { $LogName = ([string]$callStack[1].Command) -replace '\.ps1$', '' }
            }

            # Drop characters that are illegal in file names (e.g. '<ScriptBlock>' from a -Command caller)
            $invalidChars = [System.IO.Path]::GetInvalidFileNameChars()
            $LogName = -join ($LogName.ToCharArray() | Where-Object { $invalidChars -notcontains $_ })
            if (-not $LogName) { $LogName = 'CWAAScript' }

            # Refuse a directory path that runs through a junction or symlink: a planted link
            # would redirect where this (usually SYSTEM) process creates folders and files.
            # Checked on the nearest existing folder before creating anything, then again after.
            $assertNoReparsePoint = {
                param($path)
                $existing = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($path)
                while ($existing -and -not (Test-Path -LiteralPath $existing)) { $existing = Split-Path -Path $existing -Parent }
                if (-not $existing) { return }
                $directory = Get-Item -LiteralPath $existing -Force -ErrorAction Stop
                while ($directory) {
                    if ($directory.Attributes -band [System.IO.FileAttributes]::ReparsePoint) {
                        throw "'$($directory.FullName)' is a junction or symbolic link; refusing to create a log through it."
                    }
                    $directory = $directory.Parent
                }
            }
            & $assertNoReparsePoint $LogDirectory

            if (-not (Test-Path -LiteralPath $LogDirectory)) {
                $null = New-Item -Path $LogDirectory -ItemType Directory -Force -ErrorAction Stop
                Write-Debug "Initialize-CWAAScriptLog: Created log directory '$LogDirectory'."
            }
            & $assertNoReparsePoint $LogDirectory

            # Build timestamped filename (milliseconds keep runs in the same second apart)
            $timestamp = Get-Date -Format 'yyyyMMdd-HHmmss-fff'
            $logFileName = "${LogName}_${timestamp}.log"
            # Absolute file-system path: what Automate needs, and the exact file created below
            $logFilePath = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath((Join-Path -Path $LogDirectory -ChildPath $logFileName))

            # Create the file exclusively so a pre-planted file or link at the predictable
            # name is never appended to, then write the header
            [System.IO.File]::Open($logFilePath, [System.IO.FileMode]::CreateNew, [System.IO.FileAccess]::Write).Dispose()
            $created = $true
            Write-CWAAScriptLog -Message "Log initialized: $LogName" -LogPath $logFilePath -ErrorAction Stop

            $logFilePath
        }
        Catch {
            # Don't leave an empty log behind when the header write fails
            if ($created) { Remove-Item -LiteralPath $logFilePath -Force -ErrorAction SilentlyContinue }
            # Report the underlying .NET error rather than PowerShell's "Exception calling ..." wrapper
            $cause = $_.Exception
            if ($cause -is [System.Management.Automation.MethodInvocationException] -and $cause.InnerException) { $cause = $cause.InnerException }
            $wrapped = New-Object System.Exception("Failed to initialize script log in '$LogDirectory'. Error: $($cause.Message)", $cause)
            Write-Error -Exception $wrapped -Category $_.CategoryInfo.Category -TargetObject $LogDirectory
        }
    }

    End {
        Write-Debug "Exiting $($MyInvocation.InvocationName)"
    }
}
