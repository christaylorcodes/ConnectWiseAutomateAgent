function New-CWAAScriptOutput {
    <#
    .SYNOPSIS
        Creates a structured output object for ConnectWise Automate script results.
    .DESCRIPTION
        Creates a PSCustomObject representing the result of an Automate-deployed script.
        The object has Status, Result, LogPath, and Data properties. A ToString ScriptMethod
        is attached that serializes the object to the pipe-delimited format expected by
        Automate's script output parser via ConvertTo-CWAAScriptOutput.

        This replaces the legacy AutomateOutput class from CW-Automate-ScriptHelper.ps1
        with a PSCustomObject that has zero load-time side effects and works on
        PowerShell 3.0+.
    .PARAMETER Status
        The execution status. Valid values: Success, Failed, Error. Defaults to Success.
    .PARAMETER Result
        A description of the script outcome.
    .PARAMETER LogPath
        The file path to the script's log file, if logging was initialized.
    .PARAMETER Data
        Optional additional data to include in the output (e.g., EDF values).
    .EXAMPLE
        $output = New-CWAAScriptOutput
        $output.Result = 'Service is running'
        $output.ToString()
        # Returns: Status=Success|Result=Service is running|LogPath=|Data=
    .EXAMPLE
        $output = New-CWAAScriptOutput -Status 'Failed' -Result 'Service was stopped'
        $output.ToString()
        # Returns: Status=Failed|Result=Service was stopped|LogPath=|Data=
    .NOTES
        Author: Chris Taylor
        Alias: New-AutomateOutput
    .LINK
        https://github.com/christaylorcodes/ConnectWiseAutomateAgent
    .PARAMETER ProgressAction
        Determines how PowerShell responds to progress updates generated by a script, cmdlet, or provider.
    #>
    [CmdletBinding()]
    [Alias('New-AutomateOutput')]
    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSUseShouldProcessForStateChangingFunctions', '', Justification = 'Creates an in-memory PSCustomObject, no system state change.')]
    Param(
        [Parameter()]
        [ValidateSet('Success', 'Failed', 'Error')]
        [string]$Status = 'Success',

        [Parameter()]
        [string]$Result = '',

        [Parameter()]
        [string]$LogPath = '',

        [Parameter()]
        [string]$Data = ''
    )

    Begin {
        Write-Debug "Starting $($MyInvocation.InvocationName)"
    }

    Process {
        $outputObject = [PSCustomObject]@{
            PSTypeName = 'CWAAScriptOutput'
            Status     = $Status
            Result     = $Result
            LogPath    = $LogPath
            Data       = $Data
        }

        $outputObject | Add-Member -MemberType ScriptMethod -Name 'ToString' -Value {
            ConvertTo-CWAAScriptOutput -InputObject $this
        } -Force

        $outputObject
    }

    End {
        Write-Debug "Exiting $($MyInvocation.InvocationName)"
    }
}
