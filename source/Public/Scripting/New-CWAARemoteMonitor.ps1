function New-CWAARemoteMonitor {
    <#
    .SYNOPSIS
        Encodes a PowerShell scriptblock for use in a ConnectWise Automate remote monitor.
    .DESCRIPTION
        Converts a PowerShell scriptblock into a Base64-encoded command string suitable for
        pasting into an Automate remote monitor's action field. The output is a fully-formed
        command line that launches powershell.exe, decodes, and executes the scriptblock.

        The Automate remote monitor action field has an 8191 character limit. This function
        validates the encoded output does not exceed that limit.
    .PARAMETER ScriptBlock
        The PowerShell scriptblock to encode for remote monitor execution.
    .EXAMPLE
        New-CWAARemoteMonitor -ScriptBlock { Get-Service LTService | Select-Object Status }
        Returns the encoded command string ready for the monitor action field.
    .EXAMPLE
        $monitor = New-CWAARemoteMonitor -ScriptBlock { if ((Get-Service LTService).Status -ne 'Running') { exit 1 } }
        $monitor | Set-Clipboard
        Encodes the scriptblock and copies it to the clipboard.
    .NOTES
        Author: Chris Taylor
        Alias: New-CWARemoteMonitor
    .LINK
        https://github.com/christaylorcodes/ConnectWiseAutomateAgent
    .PARAMETER ProgressAction
        Determines how PowerShell responds to progress updates generated by a script, cmdlet, or provider.
    #>
    [CmdletBinding()]
    [Alias('New-CWARemoteMonitor')]
    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSUseShouldProcessForStateChangingFunctions', '', Justification = 'Returns a Base64-encoded string, no system state change.')]
    Param(
        [Parameter(Mandatory = $true)]
        [scriptblock]$ScriptBlock
    )

    Begin {
        Write-Debug "Starting $($MyInvocation.InvocationName)"
    }

    Process {
        $maxCharacters = 8191

        $encodedCommand = [Convert]::ToBase64String(
            [System.Text.Encoding]::UTF8.GetBytes($ScriptBlock.ToString())
        )

        $monitorCommand = @"
"%windir%\System32\WindowsPowerShell\v1.0\powershell.exe" "&{`$C='${encodedCommand}';[System.Text.Encoding]::UTF8.GetString([System.Convert]::FromBase64String(`$C))|iex}"
"@

        $characterCount = $monitorCommand.Length
        Write-Debug "New-CWAARemoteMonitor: Encoded command is $characterCount characters (limit: $maxCharacters)."

        if ($characterCount -gt $maxCharacters) {
            Write-Error "Encoded command is $characterCount characters, which exceeds the Automate remote monitor limit of $maxCharacters characters." -ErrorAction Stop
        }

        $monitorCommand
    }

    End {
        Write-Debug "Exiting $($MyInvocation.InvocationName)"
    }
}
