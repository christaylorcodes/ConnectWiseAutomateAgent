function Write-CWAAScriptLog {
    <#
    .SYNOPSIS
        Writes a timestamped log entry to a ConnectWise Automate script log file.
    .DESCRIPTION
        Appends a formatted, timestamped entry to the log file specified by LogPath.
        Entries follow the format: [yyyy-MM-dd HH:mm:ss] [LEVEL] Message

        Use Initialize-CWAAScriptLog to create the log file first. This function performs
        synchronous file writes via Add-Content with no external module dependency.
    .PARAMETER Message
        The log message text.
    .PARAMETER Level
        The severity level of the log entry. Valid values: INFO, WARNING, ERROR.
        Defaults to INFO.
    .PARAMETER LogPath
        The full path to the log file. Typically obtained from Initialize-CWAAScriptLog.
    .EXAMPLE
        Write-CWAAScriptLog -Message 'Processing complete' -LogPath $logPath
    .EXAMPLE
        Write-CWAAScriptLog -Message 'Service not found' -Level WARNING -LogPath $logPath
    .EXAMPLE
        Write-CWAAScriptLog -Message 'Unhandled exception' -Level ERROR -LogPath $logPath
    .NOTES
        Author: Chris Taylor
        Alias: Write-AutomateLog
    .LINK
        https://github.com/christaylorcodes/ConnectWiseAutomateAgent
    .PARAMETER ProgressAction
        Determines how PowerShell responds to progress updates generated by a script, cmdlet, or provider.
    #>
    [CmdletBinding()]
    [Alias('Write-AutomateLog')]
    Param(
        [Parameter(Mandatory = $true, Position = 0, ValueFromPipeline = $true)]
        [string]$Message,

        [Parameter()]
        [ValidateSet('INFO', 'WARNING', 'ERROR')]
        [string]$Level = 'INFO',

        [Parameter(Mandatory = $true)]
        [string]$LogPath
    )

    Begin {
        Write-Debug "Starting $($MyInvocation.InvocationName)"
    }

    Process {
        Try {
            $timestamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
            $logEntry = "[$timestamp] [$Level] $Message"
            Add-Content -LiteralPath $LogPath -Value $logEntry -Encoding UTF8 -ErrorAction Stop
            Write-Debug "Write-CWAAScriptLog: $logEntry"
        }
        Catch {
            Write-Error "Failed to write to log file '$LogPath'. Error: $($_.Exception.Message)"
        }
    }

    End {
        Write-Debug "Exiting $($MyInvocation.InvocationName)"
    }
}
