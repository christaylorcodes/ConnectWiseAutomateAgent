#requires -Version 7.0

<#
.SYNOPSIS
    Post-processes PlatyPS-generated markdown help files.

.DESCRIPTION
    Run after regenerating help with PlatyPS (New-MarkdownHelp/Update-MarkdownHelp) to clean up common PlatyPS artifacts:

    - Replaces the '{{ Fill ProgressAction Description }}' placeholder with a
      standard description.
    - Populates empty RELATED LINKS sections with the project GitHub URL and
      website.
    - Reports a summary of changes made.

    Designed to be run from the repository root.

.PARAMETER DocsPath
    Path to the PlatyPS markdown help folder. Defaults to 'Docs/Help'.

.PARAMETER GitHubUrl
    GitHub repository URL. Auto-detected from 'gh repo view' if not provided.

.PARAMETER WebsiteUrl
    Project or author website URL. Defaults to 'https://christaylor.codes'.

.EXAMPLE
    # Auto-detect everything
    ./Scripts/Update-PlatyPSDocs.ps1

.EXAMPLE
    # Explicit paths
    ./Scripts/Update-PlatyPSDocs.ps1 -DocsPath 'Docs/Help' -GitHubUrl 'https://github.com/christaylorcodes/ConnectWiseAutomateAgent'
#>
[CmdletBinding()]
param(
    [Parameter()]
    [string]$DocsPath = 'Docs/Help',

    [Parameter()]
    [string]$GitHubUrl,

    [Parameter()]
    [string]$WebsiteUrl = 'https://christaylor.codes'
)

$ErrorActionPreference = 'Stop'

# Resolve docs path
if (-not (Test-Path $DocsPath)) {
    Write-Error "Docs path '$DocsPath' not found. Generate the markdown help with PlatyPS first."
    return
}

# Auto-detect GitHub URL if not provided
if (-not $GitHubUrl) {
    try {
        # gh is a native command: a failure sets $LASTEXITCODE rather than throwing
        $ghOutput = gh repo view --json url 2>$null
        if ($LASTEXITCODE -eq 0 -and $ghOutput) { $GitHubUrl = ($ghOutput | ConvertFrom-Json).url }
    }
    catch {
        Write-Verbose "gh repo view failed: $($_.Exception.Message)"
    }
    if ($GitHubUrl) { Write-Verbose "Auto-detected GitHub URL: $GitHubUrl" }
    else { Write-Warning 'Could not auto-detect GitHub URL. RELATED LINKS will not be updated.' }
}

$ProgressActionDescription = 'Determines how PowerShell responds to progress updates generated by a script, cmdlet, or provider.'

$files = Get-ChildItem -Path $DocsPath -Filter '*.md' -File
$progressPlaceholder = '\{\{ Fill ProgressAction Description \}\}'
# RELATED LINKS is empty only when the heading is the last non-whitespace content in the file
$emptyRelatedLinks = '## RELATED LINKS\s*\z'
$stats = @{ ProgressAction = 0; RelatedLinks = 0 }

foreach ($file in $files) {
    $original = Get-Content -Path $file.FullName -Raw
    $content = $original

    if ($content -match $progressPlaceholder) {
        $content = $content -replace $progressPlaceholder, $ProgressActionDescription
        $stats.ProgressAction++
    }

    if ($GitHubUrl -and $content -match $emptyRelatedLinks) {
        $linksBlock = "## RELATED LINKS`n`n[$GitHubUrl]($GitHubUrl)`n`n[$WebsiteUrl]($WebsiteUrl)`n"
        $content = $content -replace $emptyRelatedLinks, $linksBlock
        $stats.RelatedLinks++
    }

    if ($content -ne $original) {
        Set-Content -Path $file.FullName -Value $content -NoNewline -Encoding utf8
    }
}

Write-Host "Scanned $($files.Count) docs in '$DocsPath':" -ForegroundColor Cyan
Write-Host "  ProgressAction placeholders fixed: $($stats.ProgressAction)" -ForegroundColor Green
Write-Host "  RELATED LINKS populated:           $($stats.RelatedLinks)" -ForegroundColor Green
